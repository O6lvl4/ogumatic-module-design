"""外界（ファイル・git・時計）の写し。副作用はこの箱だけ。"""
from typing import Protocol


class Fs(Protocol):
    def list_files(self, root: str, skip: set) -> list: ...
    def read_text(self, root: str, rel: str) -> str: ...
    def write_text(self, root: str, rel: str, text: str) -> None: ...
    def changed_files(self, root: str, rng: str | None) -> list: ...
    def subject(self, root: str) -> str: ...
    def today(self) -> str: ...
